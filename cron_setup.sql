-- Planner Life for Soil 7.6 - Cron setup
-- قبل از اجرا، عبارت PASTE_YOUR_CRON_SECRET_HERE را با همان Secret ثبت‌شده در Edge Functions جایگزین کن.

create extension if not exists pg_cron with schema extensions;
create extension if not exists pg_net with schema extensions;
create extension if not exists vault with schema vault;

create table if not exists public.planner_cron_deliveries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  dedupe_key text not null,
  kind text not null,
  status text not null default 'pending',
  sent_at timestamptz,
  telegram_message_id bigint,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (user_id, dedupe_key)
);

alter table public.planner_cron_deliveries enable row level security;
revoke all on public.planner_cron_deliveries from anon, authenticated;

-- اگر Secret با این نام قبلاً ساخته شده، ابتدا آن را از Dashboard > Vault حذف کن.
select vault.create_secret(
  'PASTE_YOUR_CRON_SECRET_HERE',
  'planner_cron_secret',
  'Secret used by pg_cron to invoke planner-cron Edge Function'
);

-- حذف Job قبلی با همین نام، در صورت وجود
select cron.unschedule(jobid)
from cron.job
where jobname = 'planner-telegram-every-5-minutes';

-- اجرای تابع هر ۵ دقیقه
select cron.schedule(
  'planner-telegram-every-5-minutes',
  '*/5 * * * *',
  $$
  select net.http_post(
    url := 'https://esrqfulstdqnpbaldbko.supabase.co/functions/v1/planner-cron',
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'x-cron-secret', (
        select decrypted_secret
        from vault.decrypted_secrets
        where name = 'planner_cron_secret'
        limit 1
      )
    ),
    body := jsonb_build_object('source', 'pg_cron', 'requested_at', now()),
    timeout_milliseconds := 15000
  ) as request_id;
  $$
);

-- مشاهده Job ساخته‌شده
select jobid, jobname, schedule, active
from cron.job
where jobname = 'planner-telegram-every-5-minutes';
